/**
 * Привязка смещения к пиксельной сетке экрана.
 *
 * Плавная прокрутка выдаёт дробный scrollY, а параллакс добавляет к нему своё
 * дробное смещение. В сумме текст всё время оказывается между пикселями, и
 * браузер пересглаживает глифы на каждом кадре — это заметно как дрожание,
 * особенно когда прокрутка замедляется и шаги становятся меньше пикселя.
 *
 * Округление до физического пикселя убирает дрожь, но не делает движение
 * ступенчатым: на экранах с удвоенной плотностью шаг остаётся в половину
 * логического пикселя.
 */
export function snapToPixel(value: number): number {
  const ratio = typeof window === "undefined" ? 1 : window.devicePixelRatio || 1;
  return Math.round(value * ratio) / ratio;
}
